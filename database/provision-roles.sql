SELECT format('CREATE ROLE coldchain_admin LOGIN SUPERUSER CREATEDB CREATEROLE PASSWORD %L', :'admin_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'coldchain_admin')\gexec
SELECT format('CREATE ROLE coldchain_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD %L', :'migrator_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'coldchain_migrator')\gexec
SELECT format('CREATE ROLE coldchain_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L', :'app_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'coldchain_app')\gexec
ALTER ROLE coldchain_admin WITH LOGIN SUPERUSER CREATEDB CREATEROLE PASSWORD :'admin_password';
ALTER ROLE coldchain_migrator WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'migrator_password';
ALTER ROLE coldchain_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'app_password';
