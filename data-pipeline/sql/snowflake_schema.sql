-- Snowflake Analytical Data Model
-- Based on docs/SNOWFLAKE.md

CREATE DATABASE IF NOT EXISTS COLD_CHAIN_DW;
CREATE SCHEMA IF NOT EXISTS COLD_CHAIN_DW.ANALYTICS;
USE SCHEMA COLD_CHAIN_DW.ANALYTICS;

-- 1. Dimensions
CREATE TABLE IF NOT EXISTS DIM_DATE (
    DATE_KEY INT PRIMARY KEY,
    FULL_DATE DATE NOT NULL,
    YEAR INT NOT NULL,
    QUARTER INT NOT NULL,
    MONTH INT NOT NULL,
    MONTH_NAME VARCHAR(16) NOT NULL,
    DAY_OF_MONTH INT NOT NULL,
    DAY_OF_WEEK INT NOT NULL,
    DAY_NAME VARCHAR(16) NOT NULL,
    IS_WEEKEND BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS DIM_SHIPMENT (
    SHIPMENT_KEY INT AUTOINCREMENT PRIMARY KEY,
    SHIPMENT_ID VARCHAR(64) UNIQUE NOT NULL,
    TRACKING_NUMBER VARCHAR(128) NOT NULL,
    ORIGIN VARCHAR(128) NOT NULL,
    DESTINATION VARCHAR(128) NOT NULL,
    STORAGE_PROFILE_ID VARCHAR(64) NOT NULL,
    STORAGE_PROFILE_NAME VARCHAR(64) NOT NULL,
    TARGET_MIN_C NUMERIC(5,2) NOT NULL,
    TARGET_MAX_C NUMERIC(5,2) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS DIM_LOT (
    LOT_KEY INT AUTOINCREMENT PRIMARY KEY,
    LOT_ID VARCHAR(64) UNIQUE NOT NULL,
    SHIPMENT_ID VARCHAR(64) NOT NULL,
    PRODUCT_NAME VARCHAR(128) NOT NULL,
    BATCH_NUMBER VARCHAR(64) NOT NULL,
    QUANTITY INT NOT NULL,
    INITIAL_RISK_LEVEL VARCHAR(32) NOT NULL,
    CURRENT_DISPOSITION VARCHAR(32) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS DIM_SENSOR (
    SENSOR_KEY INT AUTOINCREMENT PRIMARY KEY,
    SENSOR_ID VARCHAR(64) UNIQUE NOT NULL,
    HARDWARE_MODEL VARCHAR(64) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    REGISTERED_AT TIMESTAMP_NTZ NOT NULL
);

-- 2. Fact Tables
CREATE TABLE IF NOT EXISTS FACT_SENSOR_EVENT (
    EVENT_FACT_KEY BIGINT AUTOINCREMENT PRIMARY KEY,
    EVENT_ID VARCHAR(64) NOT NULL,
    SHIPMENT_ID VARCHAR(64) NOT NULL,
    SENSOR_ID VARCHAR(64) NOT NULL,
    SEQUENCE_NO BIGINT,
    EVENT_TIME TIMESTAMP_NTZ NOT NULL,
    INGESTION_TIME TIMESTAMP_NTZ NOT NULL,
    LATENESS_MINUTES INT NOT NULL,
    TEMPERATURE_C NUMERIC(5,2),
    EVALUATION_STATUS VARCHAR(32) NOT NULL, -- NORMAL, EXCURSION, UNKNOWN
    QUALITY_FLAG VARCHAR(32) NOT NULL,      -- VALID, LATE, OUT_OF_ORDER, QUARANTINED
    IS_DUPLICATE BOOLEAN NOT NULL,
    EXCURSION_INCIDENT_ID VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS FACT_EXCURSION (
    EXCURSION_FACT_KEY INT AUTOINCREMENT PRIMARY KEY,
    EXCURSION_ID VARCHAR(64) UNIQUE NOT NULL,
    SHIPMENT_ID VARCHAR(64) NOT NULL,
    RULE_VERSION VARCHAR(32) NOT NULL,
    SEVERITY VARCHAR(32) NOT NULL,          -- MINOR, MAJOR, CRITICAL
    STATUS VARCHAR(32) NOT NULL,            -- OPEN, UNDER_INVESTIGATION, DISPOSITIONED, CLOSED
    START_EVENT_TIME TIMESTAMP_NTZ NOT NULL,
    END_EVENT_TIME TIMESTAMP_NTZ,
    DURATION_MINUTES INT NOT NULL,
    PEAK_TEMPERATURE_C NUMERIC(5,2) NOT NULL,
    AFFECTED_LOTS_COUNT INT NOT NULL,
    CREATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS FACT_INVESTIGATION (
    INVESTIGATION_FACT_KEY INT AUTOINCREMENT PRIMARY KEY,
    INVESTIGATION_ID VARCHAR(64) UNIQUE NOT NULL,
    EXCURSION_ID VARCHAR(64) NOT NULL,
    SHIPMENT_ID VARCHAR(64) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    SLA_DUE_AT TIMESTAMP_NTZ NOT NULL,
    OPENED_AT TIMESTAMP_NTZ NOT NULL,
    CLOSED_AT TIMESTAMP_NTZ,
    IS_SLA_BREACHED BOOLEAN NOT NULL,
    HAS_CONTRADICTORY_EVIDENCE BOOLEAN NOT NULL,
    MANUAL_INSPECTIONS_COUNT INT NOT NULL
);

CREATE TABLE IF NOT EXISTS FACT_DECISION (
    DECISION_FACT_KEY INT AUTOINCREMENT PRIMARY KEY,
    DECISION_ID BIGINT UNIQUE NOT NULL,
    INVESTIGATION_ID VARCHAR(64) NOT NULL,
    EXCURSION_ID VARCHAR(64) NOT NULL,
    DECISION VARCHAR(32) NOT NULL,          -- RELEASE, HOLD, REJECT
    INVESTIGATOR_NAME VARCHAR(128) NOT NULL,
    RULE_VERSION VARCHAR(32) NOT NULL,
    AFFECTED_LOTS_COUNT INT NOT NULL,
    DECIDED_AT TIMESTAMP_NTZ NOT NULL
);

-- 3. Executive KPI View
CREATE OR REPLACE VIEW V_COLD_CHAIN_KPI AS
SELECT
    (SELECT COUNT(DISTINCT SHIPMENT_ID) FROM DIM_SHIPMENT) AS TOTAL_SHIPMENTS,
    (SELECT COUNT(*) FROM FACT_EXCURSION WHERE STATUS NOT IN ('CLOSED', 'DISPOSITIONED')) AS ACTIVE_EXCURSIONS,
    (SELECT COUNT(*) FROM FACT_EXCURSION WHERE SEVERITY = 'CRITICAL') AS CRITICAL_EXCURSIONS,
    (SELECT COUNT(DISTINCT LOT_ID) FROM DIM_LOT WHERE CURRENT_DISPOSITION != 'RELEASED') AS AFFECTED_LOTS_AT_RISK,
    (SELECT COUNT(*) FROM FACT_SENSOR_EVENT WHERE IS_DUPLICATE = TRUE) AS DUPLICATE_EVENTS_SUPPRESSED,
    (SELECT COUNT(*) FROM FACT_SENSOR_EVENT WHERE QUALITY_FLAG = 'LATE') AS LATE_EVENTS_COUNT,
    (SELECT COUNT(*) FROM FACT_SENSOR_EVENT WHERE EVALUATION_STATUS = 'UNKNOWN') AS UNKNOWN_INTERVAL_READINGS,
    (SELECT COUNT(*) FROM FACT_INVESTIGATION WHERE IS_SLA_BREACHED = TRUE) AS SLA_BREACHES,
    (SELECT AVG(DATEDIFF('minute', OPENED_AT, NVL(CLOSED_AT, CURRENT_TIMESTAMP()))) FROM FACT_INVESTIGATION) AS AVG_INVESTIGATION_DURATION_MINUTES;
